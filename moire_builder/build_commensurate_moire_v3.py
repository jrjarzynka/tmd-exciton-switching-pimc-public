def write_xyz(structure: MoireStructure, filename: str) -> None:
    structure.atoms.write(filename, format="extxyz")


def write_lammps(structure: MoireStructure, filename: str) -> None:
    from ase.io import write

    write(filename, structure.atoms, format="lammps-data")


def print_report(structure: MoireStructure) -> None:
    md = structure.metadata
    print("=" * 74)
    print(" COMMENSURATE MOIRE STRUCTURE REPORT")
    print("=" * 74)
    print(f"  (m, n)                  : ({md.m}, {md.n})")
    print(f"  twist angle             : {md.theta_deg:.8f} deg")
    print(f"  primitive cells         : {md.n_cells}")
    print(f"  atoms                   : {md.n_atoms}")
    print(f"  moire period            : {md.moire_period:.4f} A "
          f"= {md.moire_period / 10:.4f} nm")
    if md.true_hetero_period is not None:
        print(f"  unstrained hetero period: {md.true_hetero_period / 10:.4f} nm")
    print(f"  lattice constant        : {md.a_bottom:.4f} A  "
          f"(top nominal {md.a_top_nominal:.4f}, strain {md.top_layer_strain * 100:+.3f}%)")
    print(f"  interlayer distance     : {md.interlayer_d:.3f} A")
    print(f"  registry shift (frac)   : ({md.registry_shift_frac[0]:.4f}, "
          f"{md.registry_shift_frac[1]:.4f})   [AA at cell corner]")
    print("  supercell vectors (A)   :")
    for v in md.supercell_vectors:
        print(f"      [{v[0]:13.6f} {v[1]:13.6f} ]")
    print("-" * 74)
    print(f"  max deviation from ideal lattice : {md.max_deviation_from_ideal:.3e} A")
    print(f"  min interatomic distance (MIC)   : {md.min_interatomic_distance:.4f} A")
    print(f"  min M-X bond (MIC)               : {md.min_MX_bond:.4f} A")
    for w in md.warnings:
        print(f"  [warning] {w}")
    print("=" * 74)


if __name__ == "__main__":
    print_report(build_commensurate_moire(m=17, n=16))
