"""
build_commensurate_moire.py

Construction of commensurate twisted MX2 (transition-metal dichalcogenide)
bilayers, with explicit commensurability enforcement and end-to-end geometric
validation.

Version: 3.0

Changes relative to v2.0
------------------------
1. FIXED (silent, structural): the supercell vectors and the sense of the
   top-layer rotation were mutually inconsistent.  A vector v belongs to the
   coincidence-site lattice (CSL) iff  v in L  AND  R(-theta) v in L.  For
   (m, n) = (17, 16) and a +theta rotation, v = m*c1 + n*c2 fails the second
   condition, so the rotated layer was NOT periodic under the supercell it was
   wrapped into.  Atom count and nearest-neighbour checks both pass anyway, so
   the defect was invisible to v2.0's validation.  The CSL is generated by
       T1 = n*c1 + m*c2,   T2 = -m*c1 + (m + n)*c2.

2. FIXED (silent, structural): each layer is now enumerated from its OWN
   primitive vectors.  Building the top layer by rotating the bottom layer's
   in-cell sites is wrong: the CSL is invariant under R(-theta) but not under
   R(+theta), so the rotated representatives are not a valid set of coset
   representatives.  Wrapping them collapsed 102 pairs of atoms onto identical
   positions for the (17, 16) cell.

3. FIXED (physics-relevant): the rotation origin was the geometric cell centre,
   0.5*(T1 + T2), which is not a lattice site.  Rotating about a non-lattice
   point displaces the rotated lattice by (I - R) c, an arbitrary translation,
   leaving the AA stacking point undefined.  Both layers now share the origin as
   a lattice site, so AA sits at the cell corner by construction, and registry
   is changed only through an explicit rigid shift of the top layer.

4. Exact twist angle via atan2 rather than arccos (arccos loses roughly half the
   mantissa as theta -> 0, which matters for the sub-1-degree cells needed to
   reach 20 nm moire periods).

5. Validation replaced.  Commensurability is asserted algebraically; every atom
   is mapped back to its ideal lattice site; neighbour distances use the
   minimum-image convention.  v2.0 compared raw Cartesian positions, so a seam
   defect at the periodic boundary -- exactly what a non-commensurate cell
   produces -- was invisible.  Atom counting alone cannot detect any of the
   three bugs above.

6. Heterobilayer input (a_top != a_bot) is accepted but flagged: exact
   pure-twist commensuration requires a single lattice constant, so the top
   layer is strained to match and both the applied strain and the true
   unstrained heterostructure moire period are reported.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Optional, Sequence

import numpy as np
